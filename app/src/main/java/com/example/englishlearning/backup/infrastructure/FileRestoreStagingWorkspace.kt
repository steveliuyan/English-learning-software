package com.example.englishlearning.backup.infrastructure

import com.example.englishlearning.backup.restore.RestoreStagingWorkspace
import com.example.englishlearning.backup.restore.StagedRestoreSession
import java.io.File

/**
 * Isolated private scratch area (`root/<sessionId>/`) mirroring package paths:
 * `records/<type>/<id>.json` and `resources/<assetId>`. Only path-safe ids ever
 * reach this class (the validator whitelist guarantees it), and the session
 * directory is removed wholesale on clear.
 */
class FileRestoreStagingWorkspace(private val root: File) : RestoreStagingWorkspace {

    init {
        root.mkdirs()
    }

    override fun stage(session: StagedRestoreSession): Boolean = try {
        val dir = sessionDir(session.sessionId)
        dir.deleteRecursively()
        dir.mkdirs()
        session.staged.records.forEach { record ->
            File(dir, "records/${record.type}").mkdirs()
            File(dir, "records/${record.type}/${record.pathStableId}.json").writeBytes(record.json)
        }
        session.staged.resources.forEach { resource ->
            File(dir, "resources").mkdirs()
            File(dir, "resources/${resource.assetId}").writeBytes(resource.bytes)
        }
        true
    } catch (_: Exception) {
        clear(session.sessionId)
        false
    }

    override fun clear(sessionId: String) {
        sessionDir(sessionId).deleteRecursively()
    }

    override fun exists(sessionId: String): Boolean = sessionDir(sessionId).isDirectory

    /** Device-side consumers (Room writer) read the staged plaintext back from here. */
    fun sessionDir(sessionId: String): File = File(root, sessionId)

    companion object {
        /** Session ids are generated by the coordinator; defensively restricted to safe names. */
        fun isSafeSessionId(id: String): Boolean =
            id.isNotEmpty() && id.length <= 64 && id.all { it in 'a'..'z' || it in 'A'..'Z' || it in '0'..'9' || it == '-' }
    }
}
